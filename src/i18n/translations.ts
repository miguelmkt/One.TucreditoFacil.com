export type Lang = 'es' | 'pt' | 'en' | 'fr';

/** URL-prefix languages (/pt, /en, /fr). Spanish is served at root with no prefix. */
export const SUPPORTED_LANGS: Exclude<Lang, 'es'>[] = ['pt', 'en', 'fr'];
export const DEFAULT_LANG: Exclude<Lang, 'es'> = 'pt';

/** Detect browser preferred language and return nearest supported prefix lang. */
export function detectBrowserLang(): Exclude<Lang, 'es'> {
  const browser = (navigator.language || 'pt').slice(0, 2).toLowerCase();
  return (SUPPORTED_LANGS as string[]).includes(browser) ? (browser as Exclude<Lang, 'es'>) : DEFAULT_LANG;
}

